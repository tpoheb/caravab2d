public enum GameState
{
    Idle,
    InCity,
    Moving,
    DrawingCard,         // Ожидаем нажатия «Вытянуть карту».
    ResolvingEvent,      // Окно карт «во время события», до применения эффекта.
    InBattle,            // Бросок показан; доступны карты «во время битвы».
    EndingTurn,         // Повторные действия запрещены.
    WaitingForAI,       // Ожидаем последовательные ходы ИИ.
    PreparingEncounter, // Карта раскрыта; доступны карты «перед битвой/событием».
    PostEncounter,      // Результат известен; доступны карты «после битвы/события».
}
